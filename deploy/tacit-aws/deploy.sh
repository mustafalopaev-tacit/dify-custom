#!/usr/bin/env bash
# Deploy one release of the Tacit Dify fork on the EC2 host.
#
# Run by the SSM document `tacit-dify-deploy` as root:
#   deploy.sh <commit-sha> <release-dir> [deploy|rollback]
#
# <release-dir> holds `docker/` and `deploy/tacit-aws/` from that commit.
# Host settings (hostname, bucket, secret id, registry) come from
# /opt/dify/host.env, written once by the instance's user data.
set -euo pipefail

SHA="$1"
SRC="$2"
MODE="${3:-deploy}"

export HOME=/root
# shellcheck disable=SC1091
source /opt/dify/host.env

DIFY=/opt/dify/docker
CERT="$DIFY/volumes/certbot/conf/live/$TACIT_HOST/fullchain.pem"
PREV_SHA="$(cat /opt/dify/current_sha 2>/dev/null || true)"

log() { echo "[$(date -u +%FT%TZ)] $*"; }

db_rev() {
  (cd "$DIFY" && docker compose exec -T db_postgres \
    psql -U postgres -d dify -tAc 'select version_num from alembic_version' 2>/dev/null) || echo none
}

write_env() {
  local https=false
  [ -f "$CERT" ] && https=true
  local tmp="$DIFY/.env.tmp"
  umask 077
  {
    echo "# Generated by deploy/tacit-aws/deploy.sh for $SHA. Do not edit on the host."
    echo "COMPOSE_PROFILES=weaviate,postgresql,collaboration,certbot"
    echo "TACIT_ECR_REGISTRY=$TACIT_ECR_REGISTRY"
    echo "TACIT_IMAGE_TAG=$SHA"
    echo "CONSOLE_API_URL=https://$TACIT_HOST"
    echo "CONSOLE_WEB_URL=https://$TACIT_HOST"
    echo "SERVICE_API_URL=https://$TACIT_HOST"
    echo "APP_API_URL=https://$TACIT_HOST"
    echo "APP_WEB_URL=https://$TACIT_HOST"
    echo "FILES_URL=https://$TACIT_HOST"
    echo "TRIGGER_URL=https://$TACIT_HOST"
    echo "STORAGE_TYPE=s3"
    echo "S3_BUCKET_NAME=$TACIT_BUCKET"
    echo "S3_REGION=$AWS_REGION"
    echo "S3_USE_AWS_MANAGED_IAM=true"
    echo "ALLOW_REGISTER=false"
    echo "ALLOW_CREATE_WORKSPACE=false"
    echo "WEAVIATE_AUTHENTICATION_ANONYMOUS_ACCESS_ENABLED=false"
    echo "NGINX_SERVER_NAME=$TACIT_HOST"
    echo "NGINX_ENABLE_CERTBOT_CHALLENGE=true"
    echo "CERTBOT_DOMAIN=$TACIT_HOST"
    echo "NGINX_SSL_CERT_FILENAME=fullchain.pem"
    echo "NGINX_SSL_CERT_KEY_FILENAME=privkey.pem"
    echo "NGINX_HTTPS_ENABLED=$https"
    echo "EXPOSE_PLUGIN_DEBUGGING_HOST=localhost"
    # Secrets: one JSON object in Secrets Manager, written as KEY=VALUE lines.
    aws secretsmanager get-secret-value --secret-id "$TACIT_SECRET_ID" \
      --query SecretString --output text | jq -r 'to_entries[] | "\(.key)=\(.value)"'
  } > "$tmp"
  mv "$tmp" "$DIFY/.env"
}

healthy() {
  local url="https://$TACIT_HOST/console/api/ping"
  [ -f "$CERT" ] || url="http://localhost/console/api/ping"
  for _ in $(seq 1 40); do
    if curl -fsS --max-time 10 "$url" >/dev/null 2>&1 \
      && [ "$(docker inspect -f '{{.State.Health.Status}}' "$(cd "$DIFY" && docker compose ps -q api)")" = healthy ]; then
      return 0
    fi
    sleep 15
  done
  return 1
}

log "Deploying $SHA ($MODE); previous release: ${PREV_SHA:-none}"

# 1. Sync the compose files. Data under volumes/ and the generated .env stay.
mkdir -p "$DIFY" /opt/dify/bin
rsync -a --delete --exclude /volumes/ --exclude /.env --exclude /nginx/conf.d/default.conf \
  "$SRC/docker/" "$DIFY/"
rsync -a "$SRC/docker/volumes/" "$DIFY/volumes/"
install -m 0755 "$SRC"/deploy/tacit-aws/{deploy,backup,healthcheck,renew-cert}.sh /opt/dify/bin/
cd "$DIFY"

# 2. Back up Postgres before anything changes.
if docker compose ps --status running --services 2>/dev/null | grep -qx db_postgres; then
  /opt/dify/bin/backup.sh "pre-deploy-$SHA"
fi
DB_REV_BEFORE="$(db_rev)"

# 3. Write .env, pull the images and start the stack. If the pull fails (for example
#    the images for this commit were never pushed), put the previous .env back so the
#    running stack and the next reboot keep using the last good release.
[ -f .env ] && cp -p .env .env.previous
write_env
aws ecr get-login-password | docker login --username AWS --password-stdin "$TACIT_ECR_REGISTRY" >/dev/null
if ! docker compose pull --quiet; then
  log "Image pull failed for $SHA; keeping the running release ${PREV_SHA:-none}"
  [ -f .env.previous ] && mv .env.previous .env
  exit 1
fi
docker compose up -d --remove-orphans
# nginx renders its bind-mounted templates only at start; recreate it so template changes apply.
docker compose up -d --no-deps --force-recreate nginx

# 4. First deploy only: get the Let's Encrypt certificate, then switch nginx to HTTPS.
if [ ! -f "$CERT" ]; then
  log "No certificate for $TACIT_HOST yet; requesting one"
  for _ in $(seq 1 20); do curl -fsS --max-time 5 http://localhost/ >/dev/null 2>&1 && break; sleep 6; done
  docker compose run --rm --entrypoint certbot certbot certonly --noninteractive --webroot \
    --webroot-path /var/www/html -d "$TACIT_HOST" --agree-tos --register-unsafely-without-email
  write_env
  docker compose up -d --no-deps --force-recreate nginx
fi

# 5. Verify; roll back automatically only when no migration ran.
if healthy; then
  echo "$SHA" > /opt/dify/current_sha
  # shellcheck disable=SC2012
  ls -1dt /opt/dify/releases/*/ 2>/dev/null | tail -n +6 | xargs -r rm -rf
  log "Deployed $SHA; health check passed"
  exit 0
fi

log "Health check failed for $SHA"
docker compose ps --all
docker compose logs --tail 80 api nginx || true
DB_REV_AFTER="$(db_rev)"

if [ "$MODE" = rollback ] || [ -z "$PREV_SHA" ] || [ "$PREV_SHA" = "$SHA" ]; then
  log "No automatic rollback (mode=$MODE, previous=${PREV_SHA:-none})"
  exit 1
fi
if [ "$DB_REV_BEFORE" != "$DB_REV_AFTER" ]; then
  log "Migrations ran ($DB_REV_BEFORE -> $DB_REV_AFTER); not rolling back automatically."
  log "Roll back by hand: restore the pre-deploy-$SHA dump from s3://$TACIT_BUCKET/backups/postgres/ and deploy $PREV_SHA."
  exit 2
fi

log "Rolling back to $PREV_SHA"
PREV_SRC="/opt/dify/releases/$PREV_SHA"
if [ ! -d "$PREV_SRC/docker" ]; then
  mkdir -p "$PREV_SRC"
  aws s3 cp "s3://$TACIT_BUCKET/deploy/$PREV_SHA/release.tgz" - | tar -xz -C "$PREV_SRC"
fi
bash "$PREV_SRC/deploy/tacit-aws/deploy.sh" "$PREV_SHA" "$PREV_SRC" rollback || true
exit 1
